using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using LayoutFixer.Diagnostics;

namespace LayoutFixer.Input;

/// <summary>
/// Pre-computed trigger tables that drive live (mid-word) and final
/// (after a word terminator) layout auto-conversion. Each table is a plain
/// set of lowercase/normalized tokens generated offline from the full word
/// dictionaries; the runtime does no scoring, it only tests membership.
/// </summary>
internal sealed class TriggerDictionaries
{
    private const string LiveRuResource = "LayoutFixer.Dictionaries.live-triggers-ru.txt";
    private const string LiveEnResource = "LayoutFixer.Dictionaries.live-triggers-en.txt";
    private const string FinalRuResource = "LayoutFixer.Dictionaries.final-triggers-ru.txt";
    private const string FinalEnResource = "LayoutFixer.Dictionaries.final-triggers-en.txt";
    private const string FinalWordsEnResource = "LayoutFixer.Dictionaries.final-words-en.txt";

    // Keyboard / system abbreviations that leak into the offline-generated
    // tables from the source word list. Treating them as layout triggers is
    // actively harmful: typing the Russian "Секд" on a RU layout would
    // live-convert to the English word "Ctrl", and "Ые" -> "Alt". These are
    // never the intended target of a wrong-layout fix, so drop them at load
    // time. The list is conservative (only key names, not real words).
    private static readonly HashSet<string> SystemAbbreviations = new(System.StringComparer.Ordinal)
    {
        "ctrl", "alt", "shift", "tab", "esc", "escape", "enter", "return",
        "del", "delete", "ins", "insert", "home", "end", "pgup", "pgdn",
        "space", "caps", "win", "cmd", "fn", "altgr", "backspace", "prtsc",
        "break", "scroll", "num", "f1", "f2", "f3", "f4", "f5", "f6", "f7",
        "f8", "f9", "f10", "f11", "f12"
    };

    private readonly HashSet<string> _liveRu;
    private readonly HashSet<string> _liveEn;
    private readonly HashSet<string> _finalRu;
    private readonly HashSet<string> _finalEn;

    public TriggerDictionaries()
        : this(null)
    {
    }

    // `extraFinalEnglish` replaces the embedded "safe English words" table
    // (tools use it to evaluate freshly generated tables).
    public TriggerDictionaries(IEnumerable<string>? extraFinalEnglish)
    {
        Assembly assembly = typeof(TriggerDictionaries).Assembly;
        // Russian entries are stored lowercased but WITHOUT folding ё -> е.
        // "ё" sits on its own physical key (EN "`"), so a table entry such as
        // "шё" (EN "i`", impossible in English) is a completely different
        // keystroke sequence than "ше" (EN "it"). Folding both to "ше" made the
        // English words "it", "at", "other", "lt" live-convert to Russian.
        _liveRu = Load(assembly, LiveRuResource, russian: true);
        _liveEn = Load(assembly, LiveEnResource, russian: false);
        _finalRu = Load(assembly, FinalRuResource, russian: true);
        _finalEn = Load(assembly, FinalEnResource, russian: false);
        // English words of 5+ letters whose Russian-layout spelling cannot be
        // a Russian word (generated by tools/LayoutFixer.Tools). They are
        // complete-word evidence only, so they join the FINAL English table.
        if (extraFinalEnglish is null)
        {
            _finalEn.UnionWith(Load(assembly, FinalWordsEnResource, russian: false));
        }
        else
        {
            AddLines(_finalEn, extraFinalEnglish, russian: false);
        }
        Logger.Log($"TriggerDictionaries loaded: liveRu={_liveRu.Count} liveEn={_liveEn.Count} finalRu={_finalRu.Count} finalEn={_finalEn.Count}");
    }

    // Trigger files load synchronously in the constructor (they are small:
    // ~4k entries at most), so there is no async-ready gate like the legacy
    // word dictionaries had. Lookups are safe immediately after construction.
    public bool IsReady => true;

    // Key names are never the intended result of a layout fix ("Секд" must
    // not become "Ctrl"); every layer that could produce English uses this.
    public static bool IsSystemAbbreviation(string word) =>
        !string.IsNullOrEmpty(word) && SystemAbbreviations.Contains(word.ToLowerInvariant());

    public bool ContainsLiveRu(string word) => ContainsRussian(_liveRu, word);

    public bool ContainsLiveEn(string word) => ContainsEnglish(_liveEn, word);

    public bool ContainsFinalRu(string word) => ContainsRussian(_finalRu, word);

    public bool ContainsFinalEn(string word) => ContainsEnglish(_finalEn, word);

    // Exact lowercase match first. A query that contains "ё" may additionally
    // match an entry spelled with "е" ("мёд" finds "мед"), because Russian text
    // often omits the dots. The reverse is NOT allowed: a query with "е" never
    // matches an entry with "ё" (see the constructor comment).
    private static bool ContainsRussian(HashSet<string> set, string word)
    {
        if (string.IsNullOrEmpty(word))
        {
            return false;
        }

        string key = word.ToLowerInvariant();
        if (set.Contains(key))
        {
            return true;
        }

        return key.IndexOf('ё') >= 0 && set.Contains(key.Replace('ё', 'е'));
    }

    private static bool ContainsEnglish(HashSet<string> set, string word)
    {
        return !string.IsNullOrEmpty(word) && set.Contains(word.ToLowerInvariant());
    }

    private static HashSet<string> Load(Assembly assembly, string resourceName, bool russian)
    {
        var set = new HashSet<string>(System.StringComparer.Ordinal);
        using Stream? stream = assembly.GetManifestResourceStream(resourceName);
        if (stream is null)
        {
            Logger.Log($"TriggerDictionaries: embedded resource '{resourceName}' not found");
            return set;
        }

        using var reader = new StreamReader(stream, Encoding.UTF8);
        AddLines(set, ReadLines(reader), russian);
        return set;
    }

    private static IEnumerable<string> ReadLines(StreamReader reader)
    {
        string? line;
        while ((line = reader.ReadLine()) is not null)
        {
            yield return line;
        }
    }

    private static void AddLines(HashSet<string> set, IEnumerable<string> lines, bool russian)
    {
        foreach (string line in lines)
        {
            if (string.IsNullOrWhiteSpace(line))
            {
                continue;
            }

            // Files are one token per line; tolerate a trailing tab+freq column.
            int tab = line.IndexOf('\t');
            string token = (tab >= 0 ? line.Substring(0, tab) : line).Trim();
            string key = token.ToLowerInvariant();
            if (key.Length == 0)
            {
                continue;
            }

            // Drop keyboard / system abbreviations (only meaningful for the
            // English tables). Keys are lowercased, matching SystemAbbreviations.
            if (!russian && SystemAbbreviations.Contains(key))
            {
                continue;
            }

            set.Add(key);
        }
    }
}
